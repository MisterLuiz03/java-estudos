package calculadora;


public class Calculo {
    
    public double somarNumeros(double n1, double n2){
    
        return n1 + n2;
        
    }
    
    public double subtrairNumeros(double n1, double n2){
    
        return n1 - n2;
        
    }
    
    public double multiplicarNumeros(double n1, double n2){
    
        return n1 * n2;
    
    }
    
    public double dividirNumeros(double n1, double n2){
    
        return n1 / n2;
    
    }
    
    public double exponenciarNumeros(double n1, double n2){
    
        return Math.pow(n1, n2);
    
    }
    
    public double dobrarNumero(double n1){
    
        return n1 * 2;
    
    }
    
    
    
}
